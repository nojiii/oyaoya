import { TeachingScript } from '../../components/TeachingScript'
import { AppleScene } from './AppleScene'

export const title = 'あわせていくつ'

export default function AdditionApples() {
  return (
    <TeachingScript
      prepare={{
        goal: '「あわせて」が足し算の合図だとわかり、3 + 2 を数えて答えられる',
        materials: ['おはじきやブロックを5こ（なければ指でもOK）'],
        point: (
          <>
            答えを先に言わず、<strong>お子さんの手で並べて、数えさせる</strong>
            こと。
          </>
        ),
        avoid: [
          '「3たす2は5でしょ」と先に言う',
          '「なんでわからないの？」と言う',
          '間違えた瞬間に「ちがう」とだけ言う',
        ],
      }}
      turns={[
        {
          say: 'あかい りんごが 3こ、あおい りんごが 2こ あるよ。あわせて なんこ かな？',
          show: (
            <>
              <AppleScene count={5} formula="question" />
              <p>あかい りんごが 3こ、あおい りんごが 2こ。あわせて なんこ？</p>
            </>
          ),
        },
        {
          say: 'りんごの かわりに、おはじきを ならべてみようか',
          do: 'おはじきを5こ、お子さんの前に置く',
          expect: '3こ と 2こを、分けて並べられる',
          why: 'いきなり式を書かせず、まずは手で触れる物を使うと、数が「ふえる」ことを実感できます。画面はすぐに見せず、お話を思い出しながら並べてもらいます。',
          stuck: [
            {
              say: 'あかい りんごは いくつ あるかな？ おなじ かずだけ おいてみよう',
              show: <AppleScene count={5} />,
            },
            {
              do: '親が1こずつ置いて見せる',
              say: 'いっしょに おこう。1、2、3',
            },
          ],
          praise: 'じょうずに ならべられたね',
        },
        {
          say: 'ぜんぶで なんこ あるか、1こずつ さわって かぞえてみよう',
          reveal: <AppleScene count={5} split counted />,
          expect: '「1、2、3、4、5」と数えて、5こ',
          why: '1つずつ声に出して数えると、数え飛ばしや、同じものを2回数える間違いが減ります。',
          stuck: [
            {
              do: 'お子さんの指に、親の指をそえる',
              say: 'いっしょに かぞえよう。1、2…',
            },
          ],
          praise: '5こ！ よく かぞえられたね',
        },
        {
          say: '「あわせて」って いわれたら、たしざん なんだよ。しきに すると どうなるかな？',
          do: '紙と鉛筆を渡す',
          reveal: <AppleScene count={5} split formula="answer" />,
          expect: '3 + 2 = 5',
          why: '「あわせて」「ぜんぶで」が足し算の合図だと気づくと、文章題で何算をすればよいか迷わなくなります。',
          stuck: [
            {
              do: '並べたおはじきを、3こ・2こと順に指さす',
              say: '3こと 2こを あわせたね。3 たす…？',
            },
            {
              do: '親が式を書いて見せる',
              say: '3 たす 2 は 5、って かくんだよ。いっしょに よんでみよう',
            },
          ],
          praise: 'そのとおり！ 3 たす 2 は 5 だね',
        },
      ]}
      check={[
        'どうやって 5こ って わかったの？',
        'あかい りんごが 4こ だったら、あわせて なんこ？',
      ]}
    />
  )
}
