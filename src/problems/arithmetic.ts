export type ArithmeticMode = 'add' | 'carry' | 'sub' | 'borrow' | 'times'

export function arithmetic(mode: ArithmeticMode, a: number, b: number) {
  if (!Number.isInteger(a) || !Number.isInteger(b))
    throw new Error('整数を入力してください。')
  if (mode === 'borrow') {
    if (a < 11 || a > 19 || b < 1 || b > 9 || b <= a % 10)
      throw new Error(
        '最初の数は11〜19、引く数は1〜9で、一の位より大きい数にしてください。',
      )
  } else if (mode === 'sub') {
    if (a < 0 || a > 20 || b < 0 || b > a)
      throw new Error('最初の数は0〜20、引く数は0〜最初の数にしてください。')
  } else if (mode === 'add') {
    // 合計が10を超えるたし算は、繰り上がり（carry）で扱う
    if (a < 0 || b < 0 || a + b > 10)
      throw new Error('0以上で、合計が10までになる2つの数を入力してください。')
  } else if (a < 1 || a > 9 || b < 1 || b > 9) {
    throw new Error('それぞれ1〜9の数を入力してください。')
  }
  if (mode === 'carry' && a + b < 10)
    throw new Error('合計が10以上になる2つの数を入力してください。')
  const symbol =
    mode === 'sub' || mode === 'borrow' ? '−' : mode === 'times' ? '×' : '+'
  const answer = symbol === '−' ? a - b : symbol === '×' ? a * b : a + b
  const equation = `${a} ${symbol} ${b}`
  const question = `${equation} = ?`
  const why =
    mode === 'times'
      ? '同じ数のまとまりと、その何こ分かを結びつけます。'
      : '実物を動かしながら、数のまとまりと計算のつながりを伝えます。'
  let steps: { say: string; why: string; do?: string }[]
  if (mode === 'carry') {
    const need = 10 - a
    const rest = b - need
    steps = [
      {
        do: `おはじきを${a}こと${b}こに分けて並べる。`,
        say: `まず10を作ろう。${a}は、あと${need}で10になるよ。`,
        why: `${a} + ${need} = 10。最初の数を10にするために必要な数を考えます。`,
      },
      {
        say: `${b}を${need}と${rest}に分けよう。${a}に足す${need}を分けると、残りは${rest}だね。`,
        why: `${b} − ${need} = ${rest}。足す数を、10を作る分と残りに分けます。`,
      },
      {
        say: `${a}と${need}を合わせると10。10のまとまりができたね。`,
        why: `${a} + ${need} = 10。分けた数のうち、10を作る分だけを先に合わせます。`,
      },
      {
        say: `10に残りの${rest}を足すと${answer}。だから、${a}たす${b}は${answer}だよ。`,
        why: `10 + ${rest} = ${answer}。分けて残していた数も足します。`,
      },
    ]
  } else if (mode === 'borrow') {
    const ones = a - 10
    steps = [
      {
        say: `${a}を10と${ones}に分けよう。`,
        why: `${a} = 10 + ${ones}。10のまとまりを使って引く準備です。`,
      },
      {
        say: `10から${b}を引くと${10 - b}だね。`,
        why: `10 − ${b} = ${10 - b}。まず10のまとまりから引きます。`,
      },
      {
        say: `残していた${ones}を足そう。${10 - b}と${ones}で${answer}。${a}ひく${b}は${answer}だよ。`,
        why: `${10 - b} + ${ones} = ${answer}。最初に分けて残した一の位を忘れずに合わせます。`,
      },
    ]
  } else if (mode === 'sub') {
    steps = [
      { say: `まず${a}こ並べよう。ここから${b}こ取るよ。`, why },
      {
        say: `残った数を1こずつ数えよう。${answer}こ残ったね。${a}ひく${b}は${answer}だよ。`,
        why,
      },
    ]
  } else if (mode === 'times') {
    steps = [
      { say: `${a}こずつのまとまりを${b}つ作ろう。`, why },
      {
        say: `${a}こが${b}つ分だね。${Array.from({ length: b }, () => a).join('たす')}で、全部で${answer}こだよ。`,
        why,
      },
      {
        say: `これをかけ算で書くと、${a}かける${b}は${answer}、となるよ。`,
        why,
      },
    ]
  } else {
    steps = [
      { say: `${a}こと${b}こを分けて並べよう。`, why },
      // 数えるのはおはじきの画面でお子さんに任せ、台本では考え方を聞く
      { say: 'どうやって答えを見つけたの？ おしえてくれる？', why },
      {
        say: `合わせるときは、たし算を使うよ。${a}たす${b}は${answer}だね。`,
        why,
      },
    ]
  }
  const advice: Record<string, { how: string; avoid: string[] }[]> = {
    carry: [
      {
        how: `${a}こと${b}こを分けて並べ、${a}この横に10こまでの空きを示します。空きが${10 - a}こあることを一緒に確かめます。`,
        avoid: [
          'いきなり全部を数えて答えを出す',
          'どちらの数を10にするか示さずに説明する',
        ],
      },
      {
        how: `${b}この中から${10 - a}こを横によけ、残りの${b - (10 - a)}こと分けて置きます。`,
        avoid: [`「${b}を分けて」とだけ言う`, '分けた残りを隠してしまう'],
      },
      {
        how: `${a}この側に${10 - a}こを移し、10こをひとまとまりで囲みます。残りは横に置いておきます。`,
        avoid: [
          '10を作ったところで計算が終わったと伝える',
          '残りも混ぜて全部を並べ直す',
        ],
      },
      {
        how: `10のまとまりを指さしてから、残りの${b - (10 - a)}こを指さし、合わせた数を確認します。`,
        avoid: [
          '分ける前の数をもう一度足す',
          '10を作ったあと、残りを足し忘れる',
        ],
      },
    ],
    borrow: [
      {
        how: `${a}こを10このまとまりと${a - 10}こに分けて並べます。`,
        avoid: ['一の位から無理に引かせる', '分けて残した数を片づける'],
      },
      {
        how: `10このまとまりから${b}こを取り、残った${10 - b}こを示します。`,
        avoid: [
          '最初に分けた一の位から引いてしまう',
          '取ったものと残りを混ぜる',
        ],
      },
      {
        how: `10から引いた残りと、最初に残した${a - 10}こを合わせて確認します。`,
        avoid: [
          '残しておいた一の位を足し忘れる',
          '一度取った数まで戻してしまう',
        ],
      },
    ],
    sub: [
      {
        how: `${a}こ並べた中から${b}こだけを取り、取ったものを離れた場所に置きます。`,
        avoid: ['引く数だけを別に追加する', '取った数と残りを混ぜる'],
      },
      {
        how: '残っているものだけを1こずつ指さして数えます。取ったものは数えません。',
        avoid: ['取ったものも含めて数える', '残りではなく取った数を答えにする'],
      },
    ],
    times: [
      {
        how: `${a}こずつのグループを${b}つ、間を空けて並べます。`,
        avoid: [
          '1つ分の数と、いくつ分を逆にする',
          'グループごとの個数をばらばらにする',
        ],
      },
      {
        how: `グループを1つずつ指さし、${a}を${b}回足して合計を確かめます。`,
        avoid: ['まとまりを崩して全部混ぜる', '途中から違う数を足す'],
      },
      {
        how: `${a}が1つ分、${b}がいくつ分かを指さし、式と並べたものを対応させます。`,
        avoid: ['九九の答えだけを暗記させる', '何が1つ分か説明しない'],
      },
    ],
    add: [
      {
        how: `${a}こと${b}こを、2つのまとまりに分けて並べます。`,
        avoid: [
          '最初から全部混ぜて元の数が分からなくなる',
          'どちらかの数だけを用意する',
        ],
      },
      {
        how: '2つのまとまりを近づけ、1つずつ指さしながら全部の数を数えます。',
        avoid: ['同じものを2回数える', '子どもが指さす速さより先に数える'],
      },
      {
        how: `元の2つのまとまりと合計を順に示し、紙に${equation} = ${answer}と書きます。`,
        avoid: [
          '式だけを書いて実物との対応を省く',
          '答えだけを繰り返して覚えさせる',
        ],
      },
    ],
  }
  const parentNotes: Record<ArithmeticMode, string[]> = {
    add: [
      '2つの数を**別々に並べて**、それぞれを**指さして確認**しましょう。\n\nまとまりを分けると、**足す前の数**を確かめやすくなります。',
      'どう考えたか、**ゆっくり聞いて**みましょう。\n\n言葉にしにくければ、**指さしで教えて**もらっても大丈夫です。',
      '数え終わったら、答えを**一緒に確かめましょう**。\n\n**数えた結果と式**を見比べると、足し算の意味が伝わります。',
    ],
    carry: [
      '10にするには**あと何こ必要か**、考えてもらいましょう。\n\n難しければ10こ分の場所を用意し、**空いている分**を一緒に数えます。',
      '足す数を、**10を作る分と残り**に分けましょう。\n\n分けた2つを合わせると、**元の数に戻る**ことも確かめます。',
      '**10を作る分だけ**を移し、残りは横に置いておきましょう。\n\n全部を混ぜず、**10のまとまり**を囲んで見せます。',
      '**10のまとまりと残り**を、順に指さしましょう。\n\n残りも数えて、**足し忘れがないか**確かめます。',
    ],
    sub: [
      '最初に並べた数から、**引く数だけ**を取り分けましょう。\n\n**取ったものと残り**を離すと、引き算の意味が見えやすくなります。',
      '**残っているものだけ**を数え、引く前の数・取った数・残りを式で確認します。\n\n迷ったら取ったものを横によけ、**残りをもう一度**数えましょう。',
    ],
    borrow: [
      '最初の数を、**10のまとまりと一の位**に分けましょう。\n\n難しければ10こを囲み、**残りを指さして**見せます。',
      '**10のまとまりから**引く数を取り、残りを確かめましょう。\n\n最初に分けた一の位は動かさず、**あとで使う分**として横に置きます。',
      '10から引いた残りに、**残しておいた一の位**を合わせましょう。\n\n足し忘れないように、**2つを順に指さして**式を確認します。',
    ],
    times: [
      '同じ個数のまとまりを並べ、**1つ分といくつ分**を区別しましょう。\n\n難しければ1つを一緒に作り、**同じまとまり**を増やしていきます。',
      'まとまりを崩さずに指さして、**同じ数を足して**いきましょう。\n\n難しければ、**1つ分の個数**から数え直します。',
      '**1つ分といくつ分**を指さして、計算式と見比べましょう。\n\n順番に迷ったら、**並べたまとまり**に戻って確かめます。',
    ],
  }
  return {
    question,
    equation,
    answer,
    steps: steps.map((step, i) => ({
      ...step,
      ...advice[mode][i],
      parentNote: parentNotes[mode][i],
    })),
  }
}
